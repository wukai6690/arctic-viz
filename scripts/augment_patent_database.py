def main() -> None:
    payload = json.loads(PATH.read_text(encoding="utf-8"))
    rows = payload["records"]
    by_id = {r["publication_number"]: r for r in rows}
    for r in rows:
        title_zh, abstract_zh = TRANSLATIONS.get(r["publication_number"], (r.get("title", ""), r.get("abstract", "")))
        r["title_zh"] = title_zh
        r["abstract_original"] = r.get("abstract", "")
        r["abstract_zh"] = abstract_zh
        r["abstract_zh_source"] = "基于公开摘要的中文译文"
    for pub, technology, title, priority, abstract in NEW:
        if pub in by_id:
            continue
        row = {
            "publication_number": pub, "technology": technology,
            "source_url": f"https://patents.google.com/patent/{pub}/zh",
            "title": title, "title_zh": title, "country": "China", "assignee": "",
            "inventors": [], "priority_date": priority, "filing_date": priority,
            "publication_date": "", "application_number": "", "status": "",
            "classifications": [], "abstract_original": abstract,
            "abstract_zh": abstract, "abstract_zh_source": "专利公开中文原文",
            "claim_1": "",
        }
        rows.append(row); by_id[pub] = row
    payload["version"] = "arctic-patent-database-20261017-v2"
    payload["generated_at"] = "2026-10-17"
    payload["source_note"] = "公开专利元数据和摘要来自 Google Patents 的专利公开页面。中国记录优先保留页面中的中文摘要原文；非中文记录提供中文译文并保留原始摘要字段。法律状态未独立核验，样本不代表完整专利总量或国家技术实力排名。"
    payload["fields"] = ["publication_number", "technology", "title", "title_zh", "country", "assignee", "priority_date", "publication_date", "status", "classifications", "abstract_original", "abstract_zh", "abstract_zh_source", "claim_1", "source_url"]
    PATH.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    print("records", len(rows), "chinese abstracts", sum(bool(r.get("abstract_zh")) for r in rows))


if __name__ == "__main__":
    main()
