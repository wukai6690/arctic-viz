def build():
    articles=json.loads((ROOT/'data/library/articles.json').read_text(encoding='utf-8'))
    research=json.loads((ROOT/'data/reference/research.json').read_text(encoding='utf-8'))
    source_urls={s['id']:s['url'] for s in research['sources']}
    places=json.loads((ROOT/'data/reference/places.json').read_text(encoding='utf-8'))['places']
    assert set(PROFILES)=={p['id'] for p in places}
    output={}
    for pid,(lede,sections,question,compare,reason) in PROFILES.items():
        article=articles[pid]
        urls=[article['url']]
        if pid=='shanghai':urls.append(articles['jiangnan']['url'])
        urls += list(dict.fromkeys(source_urls[f['source_id']] for p in research['projects'] if pid in p['place_ids'] for f in p['facts']))
        # Local photo catalog is itself a reviewed source for reading-the-image sections.
        urls += [p['source_url'] for place in places if place['id']==pid for p in place['photos']]
        if pid=='bering':urls.append('https://www.usgs.gov/media/images/diomede-islands')
        output[pid]={'lede':lede,'sections':[{'title':title,'body':body} for title,body in sections],
            'research_question':question,'compare_id':compare,'compare_reason':reason,
            'reading_urls':list(dict.fromkeys(urls)),'article_id':article['id'],
            'source_revision':article['revision'],'edited_at':'2026-10-09',
            'credit':'中文背景导读改写自对应 Wikipedia 条目（作者：Wikipedia contributors），并结合本站已核对的照片图注与项目事实；研究问题为本站提出。',
            'license':'CC BY-SA 4.0','license_url':'https://creativecommons.org/licenses/by-sa/4.0/'}
    path=ROOT/'data/reference/place_profiles.json'
    path.write_text(json.dumps(output,ensure_ascii=False,indent=2),encoding='utf-8')
    print('PROFILES',len(output),'SECTIONS',sum(len(p['sections']) for p in output.values()))
if __name__=='__main__':build()
